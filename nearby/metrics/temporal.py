import numpy as np
import mne

from tslearn.metrics import dtw
from tslearn.barycenters import euclidean_barycenter

from ..distances.distances import distance_squared_euclidean

from ..utils.core import (
    _auto_windows,
    _get_data_type,
)

from ..utils.proc import _get_data, _apply_baseline


def within_trial_temporal(
        data,
        tmin=None,
        tmax=None,
        fmin=None,
        fmax=None,
        callback_distance=None,
        callback_centroid=None,
        mode="windows",
        window_size=0.1,
        window_step=0.1,
        picks=None,
        baseline=None,
        average=True,
        return_centroid=False,
):
    """
    Compute within-trial temporal variability.

    This metric quantifies how much the temporal pattern *within each epoch* varies
    over time. For each epoch, a temporal sequence is represented either as a set of
    time-window segments (``mode="windows"``) or as a sample-wise sequence
    (``mode="all_samples"``). A within-epoch centroid is computed via
    ``callback_centroid`` and each segment/sample is compared against the centroid
    via ``callback_distance``. The within-epoch dispersion is the mean of these
    distances, and the final score aggregates dispersions across epochs.

    The input can be either time-domain epochs (:class:`mne.epochs.Epochs`) or
    time–frequency epochs (:class:`mne.time_frequency.tfr.EpochsTFR`). For TFR input,
    power can be restricted to ``fmin``–``fmax`` (Hz) and reduced to a single time
    course per epoch/channel (e.g., by averaging across frequency) by the internal
    data extraction routine.

    Parameters
    ----------
    data : mne.epochs.Epochs | mne.time_frequency.tfr.EpochsTFR
        Epoched MNE object.

    baseline : tuple of float | None, optional
        Baseline interval in seconds (e.g., ``(-1.0, 0.0)``). If provided, baseline
        correction is applied on a copy of ``data`` before computing the metric.

    fmin, fmax : float | None, optional
        Lower and upper frequency bounds (Hz). Only used when ``data`` is
        :class:`~mne.time_frequency.tfr.EpochsTFR`. If provided, the extracted data
        are restricted to the band ``[fmin, fmax]``.

    mode : {"windows", "all_samples"}, default="windows"
        Temporal representation used within each epoch.

        - ``"windows"``: represent each epoch by a sequence of windowed segments.
          Windows are generated by ``_auto_windows`` using ``auto_window_size`` and
          ``auto_window_step`` (between ``tmin`` and ``tmax`` when provided).
        - ``"all_samples"``: represent each epoch by the full sample-wise time course
          (optionally cropped to ``[tmin, tmax]``).

    window_size : float, default=0.1
        Window length in seconds used when ``mode="windows"``.

    window_step : float, default=0.1
        Step size in seconds used when ``mode="windows"``.

    callback_distance : callable | None, optional
        Distance function used to compare a segment/sample to the within-epoch
        centroid. The callable must accept ``(x, m)`` where ``x`` is a 1D array
        representing one segment/sample and ``m`` is the centroid value returned by
        ``callback_centroid``.
        If ``None``, a default squared Euclidean distance between the segment mean
        and centroid is used.

    callback_centroid : callable | None, optional
        Function used to compute a within-epoch centroid from the per-epoch matrix
        ``X_trial`` of shape ``(n_windows, n_times)``.
        If ``None``, a default centroid computed from window/time averages is used.

    tmin, tmax : float | None, optional
        Time bounds (seconds) used to select the time region of interest. Applied
        during data extraction.

    picks : str | array_like of int | array_like of str | None, optional
        Channels to include. Passed to :meth:`mne.Epochs.pick` /
        :meth:`mne.time_frequency.EpochsTFR.pick`. If ``None``, all channels are used.

    average : bool, default=True
        If ``True``, return a scalar averaged across epochs. If ``False``, return the
        per-epoch dispersion values as an array of shape ``(n_epochs,)``.

    return_centroid : bool, default=False
        If ``True``, also return the per-epoch centroid values.

    Returns
    -------
    dispersion : float | ndarray of shape (n_epochs,)
        Within-trial temporal dispersion. If ``average=True``, a scalar (mean across
        epochs). Otherwise, an array with one value per epoch.

    centroid : ndarray, optional
        Returned only when ``return_centroid=True``. The centroid values as produced
        by ``callback_centroid`` (implementation-dependent). Note: in the current
        implementation, centroids are not accumulated and this output may be empty.

    Notes
    -----
    - The function operates on a copy of the input object (``data.copy()``) and does
      not modify ``data`` in place.
    - For ``mode="windows"``, at least two windows must be generated; otherwise a
      :class:`ValueError` is raised.
    - The exact definition of "centroid" and "distance" is fully determined by
      ``callback_centroid`` and ``callback_distance``.
    """
    type_data = _get_data_type(data)

    if not ((type_data == "EpochsTFR") or (type_data == "Epochs")):
        raise ValueError("data must be an instance of EpochsTFR or Epochs objects.")

    def _callback_centroid_default(X):
        # X.shape: n_windows, n_times
        return X.mean(1).mean(0)

    def _callback_distance_default(X, M):
        # X.shape: n_times
        # M: scaler

        # take mean over n_times in the given window
        return distance_squared_euclidean(X.mean(0), M)

    if callback_distance is None:
        callback_distance = _callback_distance_default

    if callback_centroid is None:
        callback_centroid = _callback_centroid_default

    data = data.copy()

    if baseline is not None:
        data = _apply_baseline(data, baseline)

    if picks is not None:
        data = data.pick(picks=picks)

    if mode == "windows":
        windows = _auto_windows(
            size=window_size,
            step=window_step,
            tmin=tmin,
            tmax=tmax,
        )

        if (windows.ndim != 2) or (windows.shape[0] == 1):
            raise ValueError(f"Two or more windows must be specified. {windows=}")

        _X = _get_data(
            data=data,
            domain="temporal",
            windows=windows,
            fmin=fmin,
            fmax=fmax,
            picks=picks,
            tmin=None,
            tmax=None,
        )
        # X.shape: n_windows, n_epochs, n_times

        X = _X.transpose(1, 0, 2)
        # X.shape: n_epochs, n_windows, n_times

    elif mode == "all_samples":
        X = _get_data(
            data=data,
            domain="temporal",
            fmin=fmin,
            fmax=fmax,
            picks=picks,
            tmin=tmin,
            tmax=tmax,
        )

        X = np.atleast_3d(X)
        # X.shape: n_epochs, n_windows, n_times

    else:
        raise ValueError("mode must be 'windows' or 'all_samples'")

    n_epochs, n_windows, n_times = X.shape

    dispersion, centroid_list = [], []
    for idx_trial in range(n_epochs):
        X_trial = X[idx_trial, :, :]
        # X_trial.shape: n_windows, n_times

        centroid = callback_centroid(X_trial)
        centroid_list.append(centroid)

        distances_trial = []
        for n in range(n_windows):
            d = callback_distance(X_trial[n, :], centroid)
            distances_trial.append(d)

        dispersion_within_trial = np.mean(distances_trial)

        dispersion.append(dispersion_within_trial)

    if average:
        dispersion = np.mean(dispersion)
    else:
        dispersion = np.array(dispersion)

    if return_centroid:
        return dispersion, np.array(centroid_list)

    return dispersion


def between_trial_temporal(
        data,
        tmin=None,
        tmax=None,
        fmin=None,
        fmax=None,
        callback_distance=None,
        callback_centroid=None,
        picks=None,
        baseline=None,
        average=True,
        return_centroid=False,
):
    """
    Compute between-trial temporal variability.

    This metric quantifies how much single-trial time courses differ across epochs.
    For a given channel, it extracts one 1D time course per epoch, computes a
    representative centroid time course across epochs using ``callback_centroid``,
    then measures the deviation of each epoch from the centroid using
    ``callback_distance``. The final score aggregates these deviations across epochs.

    By default, the distance is Dynamic Time Warping (DTW) from
    :func:`tslearn.metrics.dtw` and the centroid is the Euclidean barycenter from
    :func:`tslearn.barycenters.euclidean_barycenter`.

    The input can be either time-domain epochs (:class:`mne.epochs.Epochs`) or
    time–frequency epochs (:class:`mne.time_frequency.tfr.EpochsTFR`). For TFR input,
    the extracted data can be restricted to ``fmin``–``fmax`` (Hz) and reduced to a
    single time course per epoch/channel by the internal data extraction routine.

    Parameters
    ----------
    data : mne.epochs.Epochs | mne.time_frequency.tfr.EpochsTFR
        Epoched MNE object.

    baseline : tuple of float | None, optional
        Baseline interval in seconds (e.g., ``(-1.0, 0.0)``). If provided, baseline
        correction is applied on a copy of ``data`` before computing the metric.

    fmin, fmax : float | None, optional
        Lower and upper frequency bounds (Hz). Only used when ``data`` is
        :class:`~mne.time_frequency.tfr.EpochsTFR`.

    tmin, tmax : float | None, optional
        Time bounds (seconds) used to crop the extracted time courses to
        ``[tmin, tmax]``.

    picks : str | array_like of int | array_like of str | None, optional
        Channels to include. Passed to :meth:`mne.Epochs.pick` /
        :meth:`mne.time_frequency.EpochsTFR.pick`. If ``None``, all channels are used.

    callback_distance : callable | None, optional
        Distance function comparing one epoch time course to the centroid.
        Must accept ``(x, m)`` where both inputs are array-like time series.
        If ``None``, uses :func:`tslearn.metrics.dtw`.

    callback_centroid : callable | None, optional
        Function computing a centroid from the stacked epoch time courses ``X``.
        If ``None``, uses :func:`tslearn.barycenters.euclidean_barycenter`.

    average : bool, default=True
        If ``True``, return a scalar mean distance across epochs. If ``False``, return
        per-epoch distances as an array of shape ``(n_epochs,)``.

    return_centroid : bool, default=False
        If ``True``, also return the centroid time course.

    Returns
    -------
    dispersion : float | ndarray of shape (n_epochs,)
        Between-trial temporal dispersion. If ``average=True``, a scalar (mean across
        epochs). Otherwise, an array with one value per epoch.

    centroid : ndarray, optional
        Returned only when ``return_centroid=True``. Centroid time course as returned
        by ``callback_centroid`` (typically shape ``(n_times, 1)`` for tslearn
        barycenters).

    Notes
    -----
    - The function operates on a copy of the input object (``data.copy()``) and does
      not modify ``data`` in place.
    - The exact meaning of distance and centroid depends on
      ``callback_distance`` / ``callback_centroid``.
    """
    type_data = _get_data_type(data)

    if not ((type_data == "EpochsTFR") or (type_data == "Epochs")):
        raise ValueError(
            "between_trial_temporal is only implemented for EpochsTFR or Epochs objects."
        )

    if callback_distance is None:
        callback_distance = dtw

    if callback_centroid is None:
        callback_centroid = euclidean_barycenter

    data = data.copy()

    if baseline is not None:
        data = _apply_baseline(data, baseline)

    if picks is not None:
        data = data.pick(picks=picks)

    X = _get_data(
        data=data,
        domain="temporal",
        tmin=tmin,
        tmax=tmax,
        fmin=fmin,
        fmax=fmax,
        picks=picks,
    )

    centroid = callback_centroid(X)
    # mean.shape: n_times, 1

    n_epochs = X.shape[0]

    distances = []
    for m in range(n_epochs):
        x = X[m, None].T

        # x.shape: n_times, 1
        # centroid.shape: n_times, 1
        d = callback_distance(x, centroid)
        distances.append(d)

    if average:
        dispersion = np.mean(distances)
    else:
        dispersion = np.array(distances)

    if return_centroid:
        return dispersion, centroid

    return dispersion


def between_trial_group_temporal(
        data,
        tmin=None,
        tmax=None,
        fmin=None,
        fmax=None,
        callback_distance=None,
        callback_centroid=None,
        centroid=None,
        picks=None,
        baseline=None,
        average=True,
        return_centroid=False,
):
    """
    Compute between-trial-group temporal variability.

    This metric quantifies how much *group-representative* waveforms (e.g., averaged
    responses per condition) differ from each other. Each element in ``data`` is
    expected to be a group-level representative MNE object (either
    :class:`mne.Evoked` or :class:`mne.time_frequency.tfr.AverageTFR`). For each group,
    a 1D time course is extracted, a centroid time course is defined, and the
    deviation of each group waveform from the centroid is measured using a distance
    such as DTW.

    By default, the distance is Dynamic Time Warping (DTW) from
    :func:`tslearn.metrics.dtw` and the centroid is the Euclidean barycenter from
    :func:`tslearn.barycenters.euclidean_barycenter`.

    Parameters
    ----------
    data : list of mne.Evoked | list of mne.time_frequency.tfr.AverageTFR
        List of group-representative MNE objects. All entries must be of the same
        type.

    centroid : {"mean"} | mne.Evoked | mne.time_frequency.tfr.AverageTFR | None, optional
        Definition of the reference centroid waveform.

        - If an MNE object is provided, it is used directly as the centroid (after
          optional channel selection).
        - If ``None``, the centroid is computed from ``data`` using
          ``callback_centroid``.
        - Any provided centroid object must match the type of the objects in
          ``data``.

    fmin, fmax : float | None, optional
        Lower and upper frequency bounds (Hz). Only used when ``data`` contains
        :class:`~mne.time_frequency.tfr.AverageTFR`.

    tmin, tmax : float | None, optional
        Time bounds (seconds) used to crop all extracted time courses to
        ``[tmin, tmax]``.

    picks : str | array_like of int | array_like of str | None, optional
        Channels to include. Applied to the centroid (if provided as an object) and
        to every element in ``data``. If ``None``, all channels are used.

    callback_distance : callable | None, optional
        Distance function comparing one group time course to the centroid. Must
        accept ``(x, m)`` where both inputs are array-like time series.
        If ``None``, uses :func:`tslearn.metrics.dtw`.

    callback_centroid : callable | None, optional
        Function computing a centroid from the stacked group time courses.
        If ``None``, uses :func:`tslearn.barycenters.euclidean_barycenter`.

    average : bool, default=True
        If ``True``, return a scalar mean distance across groups. If ``False``,
        return per-group distances as an array of shape ``(n_groups,)``.

    return_centroid : bool, default=False
        If ``True``, also return the centroid time course.

    Returns
    -------
    dispersion : float | ndarray of shape (n_groups,)
        Between-trial-group temporal dispersion. If ``average=True``, a scalar (mean
        across groups). Otherwise, an array with one value per group.

    centroid : ndarray, optional
        Returned only when ``return_centroid=True``. Centroid time course as returned
        by ``callback_centroid`` (typically shape ``(n_times, 1)`` for tslearn
        barycenters).

    Notes
    -----
    - The function operates on copies of the input objects (``.copy()``) and does not
      modify the originals in place.
    - If ``centroid`` is provided as an MNE object, it must have the same type as the
      entries in ``data``.
    """
    type_data = _get_data_type(data)

    if type_data not in ["list_Evoked", "list_AverageTFR"]:
        raise ValueError(
            "data must be an instance of list of Evoked or AverageTFR objects."
        )

    if callback_distance is None:
        callback_distance = dtw

    if callback_centroid is None:
        callback_centroid = euclidean_barycenter

    data = [data[n].copy() for n in range(len(data))]

    if picks is not None:
        for n in range(len(data)):
            data[n] = data[n].pick(picks=picks)

    if baseline is not None:
        for n in range(len(data)):
            data[n] = _apply_baseline(data[n], baseline)

    X_list = []
    for n in range(len(data)):
        x = _get_data(
            data=data[n],
            domain="temporal",
            tmin=tmin,
            tmax=tmax,
            fmin=fmin,
            fmax=fmax,
            picks=picks,
        )
        X_list.append(x)

    if centroid is None:
        X_centroid = callback_centroid(np.array(X_list))
    else:
        type_data_centroid = _get_data_type(centroid)
        if type_data_centroid not in ["Evoked", "AverageTFR"]:
            raise ValueError(
                "centroid must be an instance of Evoked or AverageTFR objects."
            )

        if type_data_centroid not in type_data:
            # type_data expect "list_Evoked" or "list_AverageTFR"
            # while type_data_centroid expect "Evoked" or "AverageTFR"
            raise ValueError("centroid and data must be of the same type.")

        centroid = centroid.copy()

        if picks is not None:
            centroid = centroid.pick(picks=picks)
        if baseline is not None:
            centroid = _apply_baseline(centroid, baseline)

        X_centroid = _get_data(
            data=centroid,
            domain="temporal",
            tmin=tmin,
            tmax=tmax,
            fmin=fmin,
            fmax=fmax,
            picks=picks,
        )

    distances = []
    for X in X_list:
        # np.atleast_2d(X).T: n_times, 1
        # X_centroid.shape: n_times, 1
        X = np.atleast_2d(X).T
        d = callback_distance(X, X_centroid)
        distances.append(d)

    if average:
        dispersion = np.mean(distances)
    else:
        dispersion = np.array(distances)

    if return_centroid:
        return dispersion, X_centroid

    return dispersion
